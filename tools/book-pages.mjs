import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { basename, join } from 'node:path'

/**
 * Turn every score and report into page images.
 *
 * Run by hand, not by the build: it needs Ghostscript, which the CI runner
 * does not have, and the output is committed. `npm run book-pages`.
 *
 * The alternative was pdf.js, rendering each page to a canvas in the
 * browser. It is the obvious tool and it was turned down twice over.
 * Rendering ahead of time means the book opens on the first frame instead
 * of after a parse, which matters when opening it is an animation; and
 * this site's colophon claims no framework and no animation library, so
 * shipping a 300KB PDF engine to show eight pages of a choral score would
 * have made that claim start to wobble.
 *
 * 110 dpi puts an A4 page at about 910px wide, which is sharp at the size
 * a spread is read at and still about 100KB a page.
 *
 * `--manifest-only` rewrites src/data/books.ts from the images already in
 * public/pages without going near Ghostscript. The manifest grew a field
 * after the images were rendered, and re-rendering to pick it up would
 * have rewritten 13MB of JPEGs to change thirty numbers.
 */
const root = join(import.meta.dirname, '..')
const RENDER = !process.argv.includes('--manifest-only')
const out = join(root, 'public', 'pages')
const DPI = 110
const QUALITY = 75

/**
 * How big a JPEG is, read out of its own header.
 *
 * The page reader needs this: a lazily loaded image with no declared size
 * is a 2px box the loader never thinks is near the viewport, so it never
 * fetches and the page is simply missing. (That is not hypothetical — it
 * happened to the clarinet photograph.) The box is reserved from an
 * aspect ratio instead, and the ratio has to come from somewhere.
 *
 * Sixteen lines rather than a dependency: every SOFn marker but the three
 * that are not frame headers carries height then width at a fixed offset.
 */
function jpegSize(file) {
  const b = readFileSync(file)
  let i = 2
  while (i < b.length - 9) {
    if (b[i] !== 0xFF) { i++; continue }
    const m = b[i + 1]
    if (m >= 0xC0 && m <= 0xCF && m !== 0xC4 && m !== 0xC8 && m !== 0xCC) {
      return { w: b.readUInt16BE(i + 7), h: b.readUInt16BE(i + 5) }
    }
    i += 2 + b.readUInt16BE(i + 2)
  }
  throw new Error(`no frame header in ${file}`)
}

const sources = [
  ...readdirSync(join(root, 'public', 'scores')).map((f) => ['scores', f]),
  ...readdirSync(join(root, 'public', 'papers')).map((f) => ['papers', f]),
].filter(([, f]) => f.endsWith('.pdf'))

if (RENDER) rmSync(out, { recursive: true, force: true })

const manifest = {}
for (const [dir, file] of sources) {
  /* The directory is part of the slug, and has to be: a score and a
     report can have the same filename, and two of them do —
     introduction-and-rondo.pdf is both. Keyed on the basename alone, the
     reports rendered straight over the scores' images and the manifest
     recorded one page count for two different documents. */
  const slug = `${dir}/${basename(file, '.pdf')}`
  const into = join(out, slug)
  if (RENDER) {
    mkdirSync(into, { recursive: true })
    execFileSync('gs', [
      '-q', '-dNOPAUSE', '-dBATCH', '-dSAFER',
      '-sDEVICE=jpeg', `-dJPEGQ=${QUALITY}`, `-r${DPI}`,
      '-dTextAlphaBits=4', '-dGraphicsAlphaBits=4',
      `-sOutputFile=${join(into, '%03d.jpg')}`,
      join(root, 'public', dir, file),
    ])
  }
  const jpgs = readdirSync(into).filter((f) => f.endsWith('.jpg')).sort()

  /* The widest and the tallest page in the document, which are not always
     the same page: one of these is a concert programme whose pages run
     from 1150 to 1286 high. One box generous enough for all of them, with
     the images fitted inside it, costs a short page a white band at top
     and bottom — invisible, since the page it is printed on is white —
     and buys a scroll that never reflows as images arrive. */
  const w = Math.max(...jpgs.map((f) => jpegSize(join(into, f)).w))
  const h = Math.max(...jpgs.map((f) => jpegSize(join(into, f)).h))

  manifest[`/${dir}/${file}`] = { slug, pages: jpgs.length, w, h }
  console.log('%s → %d pages, %dx%d', file, jpgs.length, w, h)
}

writeFileSync(
  join(root, 'src', 'data', 'books.ts'),
  `/**
 * How many pages each document has, and where its page images live.
 *
 * Generated by tools/book-pages.mjs — run \`npm run book-pages\` after
 * adding or replacing a PDF. Checked in, because the renderer needs
 * Ghostscript and the CI runner does not have it.
 *
 * \`w\` and \`h\` are the widest and tallest page, and they are what lets
 * the phone's scroll reserve a box for a page before its bytes arrive.
 */
export type Book = { slug: string; pages: number; w: number; h: number }

export const BOOKS: Record<string, Book> = ${JSON.stringify(manifest, null, 2)}

/** The image for one page, one-based as a reader counts them. */
export const pageSrc = (slug: string, n: number) =>
  \`/pages/\${slug}/\${String(n).padStart(3, '0')}.jpg\`
`,
)
console.log('wrote src/data/books.ts')
