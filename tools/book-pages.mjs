import { execFileSync } from 'node:child_process'
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { basename, join } from 'node:path'

/**
 * Turn every score and report into page images.
 *
 * Run by hand, not by the build: it needs Ghostscript, which the CI runner
 * does not have, and the output is committed. `npm run book-pages`.
 *
 * The alternative was pdf.js, rendering each page to a canvas in the
 * browser. It is the obvious tool and it was turned down twice over.
 * Rendering ahead of time means the book opens on the first frame instead
 * of after a parse, which matters when opening it is an animation; and
 * this site's colophon claims no framework and no animation library, so
 * shipping a 300KB PDF engine to show eight pages of a choral score would
 * have made that claim start to wobble.
 *
 * 110 dpi puts an A4 page at about 910px wide, which is sharp at the size
 * a spread is read at and still about 100KB a page.
 */
const root = join(import.meta.dirname, '..')
const out = join(root, 'public', 'pages')
const DPI = 110
const QUALITY = 75

const sources = [
  ...readdirSync(join(root, 'public', 'scores')).map((f) => ['scores', f]),
  ...readdirSync(join(root, 'public', 'papers')).map((f) => ['papers', f]),
].filter(([, f]) => f.endsWith('.pdf'))

rmSync(out, { recursive: true, force: true })

const manifest = {}
for (const [dir, file] of sources) {
  /* The directory is part of the slug, and has to be: a score and a
     report can have the same filename, and two of them do —
     introduction-and-rondo.pdf is both. Keyed on the basename alone, the
     reports rendered straight over the scores' images and the manifest
     recorded one page count for two different documents. */
  const slug = `${dir}/${basename(file, '.pdf')}`
  const into = join(out, slug)
  mkdirSync(into, { recursive: true })
  execFileSync('gs', [
    '-q', '-dNOPAUSE', '-dBATCH', '-dSAFER',
    '-sDEVICE=jpeg', `-dJPEGQ=${QUALITY}`, `-r${DPI}`,
    '-dTextAlphaBits=4', '-dGraphicsAlphaBits=4',
    `-sOutputFile=${join(into, '%03d.jpg')}`,
    join(root, 'public', dir, file),
  ])
  const n = readdirSync(into).filter((f) => f.endsWith('.jpg')).length
  manifest[`/${dir}/${file}`] = { slug, pages: n }
  console.log('%s → %d pages', file, n)
}

writeFileSync(
  join(root, 'src', 'data', 'books.ts'),
  `/**
 * How many pages each document has, and where its page images live.
 *
 * Generated by tools/book-pages.mjs — run \`npm run book-pages\` after
 * adding or replacing a PDF. Checked in, because the renderer needs
 * Ghostscript and the CI runner does not have it.
 */
export type Book = { slug: string; pages: number }

export const BOOKS: Record<string, Book> = ${JSON.stringify(manifest, null, 2)}

/** The image for one page, one-based as a reader counts them. */
export const pageSrc = (slug: string, n: number) =>
  \`/pages/\${slug}/\${String(n).padStart(3, '0')}.jpg\`
`,
)
console.log('wrote src/data/books.ts')
