"""
Pull the outlines the room needs out of Bravura and write them as SVG paths.

Why not just ship the font: the glyphs live in the Private Use Area, and a
subset woff2 of a CFF font full of PUA codepoints turned out to render one of
them (cut common) as a blank with the wrong advance in Chromium, while every
tool read the outline back fine. Chasing that is not worth a web font request
for sixteen shapes. These are Bravura's own curves, inlined.

  python3 -m pip install fonttools brotli
  python3 tools/extract-bravura.py

Bravura is SIL Open Font License 1.1 (Steinberg Media Technologies).
Font coordinates are y-up on a 1000-unit em, and SMuFL defines one em as four
staff spaces — so the renderer scales by 4*gap/1000 and flips y.
"""
import pathlib
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen

SRC = 'node_modules/@fontsource/bravura/files/bravura-latin-400-normal.woff2'
OUT = pathlib.Path('src/lib/bravura.ts')

WANTED = [
    ('gClef', 0xE050, 'treble clef, origin on the G line'),
    ('fClef', 0xE062, 'bass clef, origin on the F line'),
    ('cutCommon', 0xE08B, 'alla breve, origin on the middle line'),
    ('sharp', 0xE262, 'origin at the pitch it alters'),
    ('flat', 0xE260, ''),
    ('natural', 0xE261, ''),
    ('restQuarter', 0xE4E5, 'origin on the middle line'),
    ('restEighth', 0xE4E6, ''),
    ('flagUp', 0xE240, 'origin at the tip of an up stem'),
    ('flagDown', 0xE241, 'origin at the tip of a down stem'),
    ('brace', 0xE000, 'one em tall; scale it to the system'),
]

f = TTFont(SRC)
cmap = {c: n for t in f['cmap'].tables for c, n in t.cmap.items()}
gs = f.getGlyphSet()
upm = f['head'].unitsPerEm
assert upm == 1000, upm

lines = [
    '/* GENERATED by tools/extract-bravura.py — do not edit by hand. */',
    '',
    '/**',
    ' * Bravura outlines, inlined.',
    ' *',
    ' * Bravura is the reference SMuFL font, the one Dorico engraves with, and',
    ' * these are its own curves for the eleven symbols the room draws. They are',
    ' * paths rather than a web font because the glyphs live in the Private Use',
    ' * Area, and a subset woff2 rendered one of them blank in Chromium while',
    ' * every font tool read it back intact. Eleven shapes are not worth a font',
    ' * request and a FOUT anyway.',
    ' *',
    ' * Coordinates are the font\'s own: a 1000-unit em, y pointing up. SMuFL',
    ' * defines one em as four staff spaces, so a caller draws a glyph at staff',
    ' * size `gap` by translating to the glyph\'s anchor and scaling by',
    ' * `4 * gap / 1000`, with y negated.',
    ' *',
    ' * Bravura © Steinberg Media Technologies, SIL Open Font License 1.1.',
    ' */',
    'export const UPM = 1000',
    '',
    'export const PATH = {',
]
for name, cp, note in WANTED:
    gname = cmap[cp]
    pen = SVGPathPen(gs)
    gs[gname].draw(pen)
    d = pen.getCommands()
    if note:
        lines.append(f'  /** U+{cp:04X} — {note} */')
    else:
        lines.append(f'  /** U+{cp:04X} */')
    lines.append(f"  {name}: '{d}',")
lines += ['} as const', '']
lines += [
    '/** Ink bounds in font units, [xMin, yMin, xMax, yMax], y up. Lets a',
    ' *  caller centre a glyph on a beat without guessing its width. */',
    'export const BBOX: Record<GlyphName, [number, number, number, number]> = {',
]
for name, cp, _ in WANTED:
    bp = BoundsPen(gs)
    gs[cmap[cp]].draw(bp)
    x0, y0, x1, y1 = bp.bounds
    lines.append(f'  {name}: [{x0}, {y0}, {x1}, {y1}],')
lines += ['}', '', 'export type GlyphName = keyof typeof PATH', '']
OUT.write_text('\n'.join(lines), encoding='utf-8')
print(OUT, OUT.stat().st_size, 'bytes')
